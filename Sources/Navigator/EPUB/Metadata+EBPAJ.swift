import Foundation
import ReadiumShared

extension Metadata {
    /// Indicates whether the publication follows the Japanese EBPAJ EPUB 3
    /// production guide, from one of these items in the OPF package:
    ///
    /// - version 1: `<dc:description id="ebpaj-guide">ebpaj-guide-1.0</dc:description>`
    /// - version 1.1: `<meta property="ebpaj:guide-version">1.1</meta>`
    ///
    /// https://github.com/readium/css/blob/develop/css/dist/ReadMe.md#ebpaj-polyfill
    var isEBPAJ: Bool {
        description == "ebpaj-guide-1.0"
            || otherMetadata["http://www.ebpaj.jp/guide-version"] != nil
            // Key of a manifest generated by the Readium Go toolkit when the
            // `ebpaj` prefix is not declared in the OPF package.
            || otherMetadata["ebpaj:guide-version"] != nil
    }
}
