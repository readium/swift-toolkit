# Validation

XHTML = "{http://www.w3.org/1999/xhtml}"


def validate(documents: dict[str, str], resources: list[Resource], files: set[str]):
    """Fails the run on a malformed document, a duplicate id or a dangling link.

    `files` holds every path packaged under `EPUB/`, relative to that folder.
    """
    seen_cases: set[str] = set()
    for resource in resources:
        for case in resource.cases:
            if case.id in seen_cases:
                raise ValidationError(f"duplicate case id '{case.id}'")
            seen_cases.add(case.id)

    for filename, content in documents.items():
        try:
            root = ElementTree.fromstring(content)
        except ElementTree.ParseError as error:
            raise ValidationError(f"{filename}: not well-formed XML: {error}")

        ids: set[str] = set()
        for element in root.iter():
            identifier = element.get("id")
            if identifier is not None:
                if identifier in ids:
                    raise ValidationError(
                        f"{filename}: duplicate element id '{identifier}'"
                    )
                ids.add(identifier)

            for attribute in ("src", "href"):
                link = element.get(attribute)
                if link is None:
                    continue
                if re.match(r"^[a-zA-Z][a-zA-Z0-9+.-]*:", link):
                    # Any absolute URL: http(s), but also the mailto: links
                    # some cases use to pin the scheme filtering down.
                    continue
                # Resolve the same way a reading system would: drop the
                # fragment, then the `./` prefix some cases use to pin down
                # href normalization.
                target = link.split("#", 1)[0].removeprefix("./")
                if target == "":
                    # Empty and fragment-only links stay inside the document;
                    # some cases use them deliberately.
                    continue
                if target not in files:
                    raise ValidationError(
                        f"{filename}: {attribute}=\"{link}\" does not resolve "
                        "to a packaged file"
                    )




def write_fixtures(directory: Path, documents: dict[str, str]):
    """Replaces `directory` with the generated XHTML.

    The directory is wiped first so that renaming a resource in the manifest
    does not leave a stale document behind for a test suite to pick up.
    """
    if directory.exists():
        shutil.rmtree(directory)
    directory.mkdir(parents=True)
    for filename, content in documents.items():
        (directory / filename).write_text(content, encoding="utf-8")


def write_epub(members: dict[str, str], assets: list[str]):
    """Writes the EPUB straight to a zip, with no exploded copy on disk.

    Entry timestamps are fixed, so regenerating an unchanged manifest produces
    a byte-identical archive and no diff noise.
    """
    with zipfile.ZipFile(EPUB_PATH, "w") as archive:

        def add(name: str, data: bytes, compress: int = zipfile.ZIP_DEFLATED):
            info = zipfile.ZipInfo(name, date_time=(2026, 1, 1, 0, 0, 0))
            info.compress_type = compress
            archive.writestr(info, data)

        # The mimetype entry must come first and be stored uncompressed.
        add("mimetype", b"application/epub+zip", zipfile.ZIP_STORED)

        for name in sorted(members):
            add(name, members[name].encode("utf-8"))
        for asset in assets:
            add(f"EPUB/assets/{asset}", (ASSETS / asset).read_bytes())


# epubcheck

BASELINE_PATH = HERE / "epubcheck-baseline.txt"

MESSAGE_PATTERN = re.compile(
    r"^(ERROR|WARNING)\(([A-Z]+-\d+)\): (?:\S*/)?(\S+?)\([-\d]+,[-\d]+\): (.*)$"
)


def run_epubcheck(update_baseline: bool) -> int:
    """Diffs epubcheck's output against the committed baseline.

    Several cases pin down how we handle markup that is *deliberately*
    malformed — dangling IDREFs, uppercase ARIA values, `role` token lists — so
    the sample cannot be epubcheck-clean without dropping the behaviour it
    exists to document. The baseline keeps the check meaningful anyway: any
    message that is not already accounted for fails the run.

    Line and column numbers are dropped so that reordering or re-wording a case
    does not churn the baseline.
    """
    if shutil.which("epubcheck") is None:
        print("epubcheck not on the PATH, skipping validation.")
        return 0

    output = subprocess.run(
        ["epubcheck", str(EPUB_PATH)], capture_output=True, text=True
    )
    found = sorted(
        f"{match.group(1)}({match.group(2)}) {match.group(3)}: {match.group(4)}"
        for line in (output.stdout + output.stderr).splitlines()
        if (match := MESSAGE_PATTERN.match(line.strip()))
    )

    if update_baseline:
        BASELINE_PATH.write_text(
            "# Expected epubcheck messages, one per deliberately invalid case.\n"
            "# Refresh with `python3 generate.py --update-epubcheck-baseline`.\n"
            + "".join(f"{message}\n" for message in found),
            encoding="utf-8",
        )
        print(f"Wrote {len(found)} expected epubcheck messages to the baseline.")
        return 0

    expected = sorted(
        line
        for line in BASELINE_PATH.read_text(encoding="utf-8").splitlines()
        if line and not line.startswith("#")
    )
    if found == expected:
        print(f"epubcheck: {len(found)} expected messages, no new ones.")
        return 0

    for message in sorted(set(found) - set(expected)):
        print(f"error: unexpected epubcheck message: {message}", file=sys.stderr)
    for message in sorted(set(expected) - set(found)):
        print(f"error: baselined epubcheck message no longer reported: {message}", file=sys.stderr)
    print(
        "Fix the markup, or refresh the baseline with "
        "`make accname-sample-baseline`.",
        file=sys.stderr,
    )
    return 1


def main() -> int:
    resources = load_manifest(HERE / "cases.toml")
    assets = sorted(path.name for path in ASSETS.iterdir() if path.is_file())

    documents = {
        resource.filename: render_document(resource) for resource in resources
    }
    nav = render_nav(resources)

    members = {
        "META-INF/container.xml": CONTAINER_XML,
        "EPUB/package.opf": render_package(resources, assets),
        "EPUB/nav.xhtml": nav,
        "EPUB/styles.css": STYLES_CSS,
        **{f"EPUB/{name}": content for name, content in documents.items()},
    }

    files = {name[len("EPUB/") :] for name in members if name.startswith("EPUB/")}
    files |= {f"assets/{asset}" for asset in assets}

    try:
        validate({**documents, "nav.xhtml": nav}, resources, files)
    except ValidationError as error:
        print(f"error: {error}", file=sys.stderr)
        return 1

    write_fixtures(SWIFT_FIXTURES_DIR, documents)
    write_fixtures(JS_FIXTURES_DIR, documents)
    write_epub(members, assets)

    total = sum(len(resource.cases) for resource in resources)
    skipped = sum(
        1 for resource in resources for case in resource.cases if case.skipped
    )
    print(
        f"Wrote {len(documents)} documents, {total} cases "
        f"({skipped} skipped) to:\n"
        f"  {SWIFT_FIXTURES_DIR.relative_to(REPO)}\n"
        f"  {JS_FIXTURES_DIR.relative_to(REPO)}\n"
        f"  {EPUB_PATH.relative_to(REPO)}"
    )

    return run_epubcheck(update_baseline="--update-epubcheck-baseline" in sys.argv)


if __name__ == "__main__":
    sys.exit(main())
